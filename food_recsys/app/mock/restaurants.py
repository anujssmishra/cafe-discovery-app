async def seed_restaurants(session: AsyncSession) -> int:
    """Populate database with 80 restaurants (32 from cafe_app + 48 multi-cuisine)."""
    count = 0
    
    # 1. Insert 32 cafe app seeds
    for cafe in CAFE_APP_SEEDS:
        stmt = select(Restaurant).where(Restaurant.id == cafe["id"])
        res = await session.execute(stmt)
        existing = res.scalar_one_or_none()
        if not existing:
            r = Restaurant(
                id=cafe["id"],
                name=cafe["name"],
                city=cafe["city"],
                area=cafe["area"],
                address=cafe["address"],
                latitude=cafe["latitude"],
                longitude=cafe["longitude"],
                cuisines=cafe["cuisines"],
                price_band=cafe["price_band"],
                source=cafe["source"],
                avg_rating=cafe["avg_rating"],
                is_active=True,
            )
            session.add(r)
            count += 1

    # 2. Insert 48 additional diverse restaurants
    for rest in ADDITIONAL_RESTAURANTS:
        stmt = select(Restaurant).where(Restaurant.name == rest["name"])
        res = await session.execute(stmt)
        existing = res.scalar_one_or_none()
        if not existing:
            r = Restaurant(
                name=rest["name"],
                city=rest["city"],
                area=rest["area"],
                address=rest["address"],
                cuisines=rest["cuisines"],
                price_band=rest["price_band"],
                source="manual",
                avg_rating=rest["avg_rating"],
                is_active=True,
            )
            session.add(r)
            count += 1

    await session.commit()
    return count
